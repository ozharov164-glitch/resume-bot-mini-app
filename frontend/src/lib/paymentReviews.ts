export function buildPaymentReview(seed: number): PaymentReview {
  const mix = hash32(seed * 2654435761);
  const profession = PROFESSIONS[mix % PROFESSIONS.length];
  const city = CITIES[Math.floor(mix / 31) % CITIES.length];
  const text = REVIEW_BODIES[Math.floor(mix / 997) % REVIEW_BODIES.length];
  return {
    id: `pr-${seed}-${mix}`,
    text,
    role: `${profession}, ${city}`,
  };
}

function normalizeProfession(value: string): string {
  return value.trim().toLowerCase();
}

function findProfessionMatchedReview(bucket: number, profession: string): PaymentReview | null {
  const needle = normalizeProfession(profession);
  if (!needle) return null;
  for (let i = 0; i < 64; i++) {
    const seed = (bucket * 104729 + i * 1363) % PAYMENT_REVIEW_POOL_SIZE;
    const review = buildPaymentReview(seed);
    if (normalizeProfession(review.role).includes(needle)) {
      return review;
    }
  }
  return null;
}

export function getPaymentReviewsForBucket(
  bucket: number,
  count = PAYMENT_REVIEW_DISPLAY_COUNT,
  preferredProfession?: string,
): PaymentReview[] {
  const base = (bucket * 104729) % PAYMENT_REVIEW_POOL_SIZE;
  const picked: PaymentReview[] = [];
  const seen = new Set<string>();

  const preferred = preferredProfession
    ? findProfessionMatchedReview(bucket, preferredProfession)
    : null;
  if (preferred) {
    picked.push(preferred);
    seen.add(preferred.id);
  }

  for (let idx = 0; picked.length < count && idx < PAYMENT_REVIEW_POOL_SIZE; idx++) {
    const seed = (base + idx * 1363) % PAYMENT_REVIEW_POOL_SIZE;
    const review = buildPaymentReview(seed);
    if (seen.has(review.id)) continue;
    seen.add(review.id);
    picked.push(review);
  }

  return picked;
}
