def promo_prompt_text() -> str:
    return (
        "🎟 <b>Активация промокода</b>\n\n"
        "Отправьте промокод одним сообщением — скидка сохранится "
        "и автоматически применится при оплате резюме.\n\n"
        "Пример: <code>BLOG10</code>"
    )


def promo_activated_text(code: str, discount: int, *, already_active: bool = False) -> str:
    prefix = "✅ Промокод уже активирован" if already_active else "✅ Промокод активирован"
    return (
        f"{prefix}: <b>{html.escape(code)}</b>\n"
        f"Скидка <b>{discount}%</b> будет применена при оплате.\n\n"
        "Теперь создайте резюме — на шаге оплаты цена уже будет со скидкой."
    )


def promo_invalid_text() -> str:
    return "❌ Промокод не найден или недействителен. Проверьте написание и попробуйте снова."
